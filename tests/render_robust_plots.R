source("R/engine.R"); source("R/plots.R")
d <- read.csv("data/california_prop99.csv", check.names = FALSE)
Y <- as.matrix(d[, -1]); rownames(Y) <- d$Year; yrs <- as.integer(d$Year)
pre <- which(yrs <= 1988); post <- which(yrs >= 1989)
main <- scm_fit(Y, "California", pre, post, starts = 5); att <- scm_att(main)
loo <- scm_loo(Y, "California", pre, post, starts = 2)
tm <- scm_timing(Y, "California", 1989, starts = 2)
pl2 <- scm_prelength(Y, "California", 1989, starts = 2)
it2 <- scm_intime(Y, "California", 1989, starts = 2)
out <- "tests/out"; dir.create(out, showWarnings = FALSE)
png(file.path(out, "loo.png"), 900, 800, res = 120); scm_plot_loo(loo, att); dev.off()
png(file.path(out, "timing.png"), 900, 600, res = 120); scm_plot_scenario(tm, att, "Treatment year", "Treatment timing sensitivity"); dev.off()
png(file.path(out, "intime.png"), 900, 600, res = 120); scm_plot_scenario(it2, att, "Fake treatment year", "In-time placebo"); dev.off()
cat("rendered\n")
