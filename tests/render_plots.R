source("R/engine.R"); source("R/plots.R")
d <- read.csv("data/california_prop99.csv", check.names = FALSE)
Y <- as.matrix(d[, -1]); rownames(Y) <- d$Year; yrs <- as.integer(d$Year)
pre <- which(yrs <= 1988); post <- which(yrs >= 1989)
fit <- scm_fit(Y, "California", pre = pre, post = post, starts = 5)
pl  <- scm_placebo(Y, "California", pre = pre, post = post, starts = 1)
out <- "tests/out"; dir.create(out, showWarnings = FALSE)
png(file.path(out, "paths.png"), 900, 600, res = 120); scm_plot_paths(fit, ylab = "Cigarette sales per capita"); dev.off()
png(file.path(out, "gaps.png"), 900, 600, res = 120); scm_plot_gaps(fit, placebo = pl); dev.off()
png(file.path(out, "weights.png"), 900, 600, res = 120); scm_plot_weights(fit); dev.off()
cat("rendered\n")
cat("placebos kept:", sum(pl$placebo_pre_rmspe <= 2 * fit$rmspe_pre), "of", length(pl$placebo_pre_rmspe), "\n")
