# Figures: each ggplot2 figure builds and prints with the Prop 99 results.
root <- normalizePath(file.path(testthat::test_path(), "..", ".."))

testthat::test_that("ggplot2 figures build from the slim states", {
  withr::local_dir(root)
  source("R/engine.R", local = TRUE)
  source("R/plots.R", local = TRUE)
  d <- read.csv("data/california_prop99.csv", check.names = FALSE)
  Y <- as.matrix(d[, -1]); rownames(Y) <- d$Year; yrs <- as.integer(d$Year)
  pre <- which(yrs <= 1988); post <- which(yrs >= 1989)
  fit <- scm_fit(Y, "California", pre = pre, post = post, starts = 2)
  pl  <- scm_placebo(Y, "California", pre = pre, post = post, starts = 1)
  pdf_file <- tempfile(fileext = ".pdf"); grDevices::pdf(pdf_file)
  on.exit({ grDevices::dev.off(); unlink(pdf_file) }, add = TRUE)
  testthat::expect_s3_class(scm_plot_paths(scm_paths_state(fit), ylab = "Sales"), "ggplot")
  print(scm_plot_paths(scm_paths_state(fit)))
  g <- scm_plot_gaps(scm_gaps_state(fit, scm_placebo_slim(pl), k = 2))
  testthat::expect_s3_class(g, "ggplot"); print(g)
  testthat::expect_s3_class(scm_plot_weights(fit$weights), "ggplot")
  loo <- scm_loo(Y, "California", pre, post, starts = 1, only = c("Utah", "Nevada"))
  print(scm_plot_loo(loo, scm_att(fit)))
  tm <- scm_timing(Y, "California", 1989, offsets = c(-2, 1), starts = 1)
  print(scm_plot_scenario(tm, scm_att(fit), "Treatment year"))
  testthat::expect_true(TRUE)
})
